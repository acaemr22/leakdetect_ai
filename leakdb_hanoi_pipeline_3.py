    all_X_seq = []
    all_y_seq = []

    for s in range(n_scenarios):
        start_idx = s * windows_per_scenario
        end_idx = start_idx + windows_per_scenario

        # Get this scenario's features and labels
        X_sc = X_feat[start_idx:end_idx]  # (windows_per_scenario, 466)
        y_sc = y_feat[start_idx:end_idx]

        # Create sequences of consecutive windows
        for i in range(LSTM_SEQ_LEN, len(X_sc)):
            seq = X_sc[i - LSTM_SEQ_LEN:i]  # (8, 466)
            label = 1 if np.any(y_sc[i - LSTM_SEQ_LEN:i] > 0) else 0
            all_X_seq.append(seq)
            all_y_seq.append(label)

