# ── Build 1D-CNN model ──
# Input: (batch, 8, 466) — 8 time steps, 466 features per step
# Conv1D treats dim 1 as temporal, dim 2 as features/channels

inputs = keras.layers.Input(shape=(X_train_cnn.shape[1], X_train_cnn.shape[2]))

# Block 1
x = keras.layers.Conv1D(256, kernel_size=3, padding='same')(inputs)
x = keras.layers.BatchNormalization()(x)
x = keras.layers.ReLU()(x)
x = keras.layers.Dropout(0.15)(x)

# Block 2
x = keras.layers.Conv1D(128, kernel_size=3, padding='same')(x)
x = keras.layers.BatchNormalization()(x)
x = keras.layers.ReLU()(x)
x = keras.layers.Dropout(0.15)(x)

# Block 3
x = keras.layers.Conv1D(64, kernel_size=3, padding='same')(x)
x = keras.layers.BatchNormalization()(x)
x = keras.layers.ReLU()(x)

# Global pooling: avg + max concatenated
avg_pool = keras.layers.GlobalAveragePooling1D()(x)
max_pool = keras.layers.GlobalMaxPooling1D()(x)
x = keras.layers.Concatenate()([avg_pool, max_pool])  # (batch, 128)

# Classifier
x = keras.layers.Dense(64, activation='relu')(x)
x = keras.layers.Dropout(0.2)(x)
x = keras.layers.Dense(32, activation='relu')(x)
outputs = keras.layers.Dense(1, activation='sigmoid')(x)

