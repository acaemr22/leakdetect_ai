"""## §3 — Feature Engineering

We use a **sliding window** approach over each scenario's SCADA time series.  
The Hanoi network has ~66 sensor channels, so with 7 statistical features per channel plus 4 temporal features, each window produces **~466 features**.

### Per-sensor features (×66 channels):
- Mean, Std, Min, Max, Slope, Delta, Skewness

### Global features:
- Hour of day (sin/cos), Day of week (sin/cos)
"""

from scipy.stats import skew as scipy_skew

WINDOW_SIZE = 48
WINDOW_STRIDE = 6
TIMESTEP_MIN = 30

# Precompute time axis constants (never changes)
_T_AXIS = np.arange(WINDOW_SIZE, dtype=np.float64)
_T_MEAN = _T_AXIS.mean()
_T_VAR = np.mean((_T_AXIS - _T_MEAN) ** 2)


def extract_features_from_scenario(X, y):
    """Fully vectorized feature extraction — no per-sensor loops."""
    T = X.shape[0]
    if T < WINDOW_SIZE:
        return None, None

    ends = np.arange(WINDOW_SIZE, T, WINDOW_STRIDE)
    n_windows = len(ends)
    n_sensors = X.shape[1]
    n_stats = 7
    n_feats = n_sensors * n_stats + 4  # +4 for temporal

    all_feats = np.empty((n_windows, n_feats), dtype=np.float32)
    all_labels = np.empty(n_windows, dtype=np.int8)

    for i, end in enumerate(ends):
        w = X[end - WINDOW_SIZE:end]

        means = w.mean(axis=0)
        stds = w.std(axis=0)
        mins = w.min(axis=0)
        maxs = w.max(axis=0)
        deltas = w[-1] - w[0]
        slopes = np.dot(_T_AXIS - _T_MEAN, w - means) / _T_VAR
        safe = stds > 1e-10
        sk = np.zeros(n_sensors, dtype=np.float32)
        if safe.any():
            sk[safe] = scipy_skew(w[:, safe], axis=0)

        all_feats[i, :n_sensors * n_stats] = np.column_stack(
            [means, stds, mins, maxs, slopes, deltas, sk]
        ).ravel()

        # Temporal features
        minutes = (end - 1) * TIMESTEP_MIN
        hour = (minutes / 60) % 24
        day = (minutes / 1440) % 7
        all_feats[i, -4] = np.sin(2 * np.pi * hour / 24)
        all_feats[i, -3] = np.cos(2 * np.pi * hour / 24)
        all_feats[i, -2] = np.sin(2 * np.pi * day / 7)
        all_feats[i, -1] = np.cos(2 * np.pi * day / 7)

        all_labels[i] = 1 if np.any(y[end - WINDOW_SIZE:end] > 0) else 0

    return all_feats, all_labels


