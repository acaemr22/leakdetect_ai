# ── §5c — LSTM Data Preparation ──
# LSTM needs raw 3D sequences (N, timesteps, sensors), NOT the pre-computed features.
# We split by scenario (0-799 train, 800-999 test) to avoid data leakage.
# NOTE: This means LSTM's test set differs from RF/XGBoost's test set.

import shutil

LSTM_TRAIN_FILE = 'lstm_train.npz'
LSTM_TEST_FILE = 'lstm_test.npz'
LSTM_WINDOW = 48    # 24 hours
LSTM_STRIDE = 2    # 12 hours (larger than RF's 3h to manage memory)

TRAIN_SCENARIOS = range(0, 800)    # first 800 scenarios
TEST_SCENARIOS = range(800, 1000)  # last 200 scenarios


def create_sequences_from_scenario(X, y):
    """Slice raw time series into 3D windows for LSTM."""
    T = X.shape[0]
    if T < LSTM_WINDOW:
        return None, None

    sequences = []
    labels = []
    for end in range(LSTM_WINDOW, T, LSTM_STRIDE):
        start = end - LSTM_WINDOW
        sequences.append(X[start:end])
        labels.append(1 if np.any(y[start:end] > 0) else 0)

    if not sequences:
        return None, None
    return np.array(sequences, dtype=np.float32), np.array(labels, dtype=np.int8)


def process_batches_for_lstm(scenario_range, label):
    """Load raw batches and create sequences for a given scenario range."""
    all_X, all_y = [], []
    n_ok = 0
    local_tmp = '/content/tmp_lstm_batch.npz'
    scenario_set = set(scenario_range)

    for i, fname in enumerate(batch_files):
        if not ckpt_exists(fname):
            continue

        print(f'  [{label}] Batch {i+1}/{len(batch_files)}: ', end='', flush=True)

        shutil.copy(ckpt_path(fname), local_tmp)
        data = np.load(local_tmp, allow_pickle=True)
        X_list, y_list = data['X_list'], data['y_list']
        scenario_ids = data['scenario_ids']

        batch_count = 0
        for j in range(len(X_list)):
            sid = int(scenario_ids[j])
            if sid not in scenario_set:
                continue

            X_sc = np.array(X_list[j], dtype=np.float32)
            y_sc = np.array(y_list[j], dtype=np.float64)
            if y_sc.ndim > 1:
                y_sc = y_sc.ravel()
            if np.any(np.isnan(X_sc)) or np.any(np.isinf(X_sc)):
                continue

            seqs, labs = create_sequences_from_scenario(X_sc, y_sc)
            if seqs is not None:
                all_X.append(seqs)
                all_y.append(labs)
                batch_count += 1
