    del all_X_seq, all_y_seq
    gc.collect()

    print(f'  Total sequences: {X_all_seq.shape}')

    # Split: first 80% scenarios train, last 20% test
    split_idx = int(0.8 * n_scenarios) * (windows_per_scenario - LSTM_SEQ_LEN)
    X_train_lstm = X_all_seq[:split_idx]
    y_train_lstm = y_all_seq[:split_idx]
    X_test_lstm = X_all_seq[split_idx:]
    y_test_lstm = y_all_seq[split_idx:]

    del X_all_seq, y_all_seq
    gc.collect()

    # Save
    print('  Saving to Drive...', flush=True)
    np.savez_compressed(ckpt_path(LSTM_TRAIN_FILE), X=X_train_lstm, y=y_train_lstm)
    np.savez_compressed(ckpt_path(LSTM_TEST_FILE), X=X_test_lstm, y=y_test_lstm)

